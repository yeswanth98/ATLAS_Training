public class Task020 {
    public static void main(String[] args) {
        char[] Name = {'Y','e','s','w','a','n','t','h'};
        int n = Name.length;
        System.out.println(Name);
        System.out.println("There are "+n+" characters in my name");
        for (int i=0; i<n; i++){
            System.out.println(Name[i]);
        }
    }
}
